const assert=require('node:assert/strict');
const p=require('../app/service/profiles');const n=require('../app/service/network');
const uuid='11111111-2222-4333-8444-555555555555';
const link='vless://'+uuid+'@example.com:443?encryption=none&security=reality&sni=example.org&fp=chrome&pbk=abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQ&sid=abcd&type=tcp&flow=xtls-rprx-vision#Test%20Reality';
const server=p.parse(link),c=p.config(server);
assert.equal(server.name,'Test Reality');assert.equal(c.outbounds[0].settings.vnext[0].users[0].flow,'xtls-rprx-vision');
assert.equal(c.outbounds[0].streamSettings.realitySettings.password,server.publicKey);
assert.equal(c.outbounds[0].streamSettings.sockopt.mark,511);
assert.equal(c.inbounds[0].listen,'127.0.0.1');assert.equal(c.inbounds[1].settings.followRedirect,true);
assert.equal(p.parseMany(Buffer.from(link+'\n'+link).toString('base64')).length,2);
assert.equal(p.uniqueName('Test',[]),'Test');
assert.equal(p.uniqueName('Test',[{name:'Test'},{name:'Test (1)'},{name:'Test (3)'}]),'Test (2)');
assert.equal(p.uniqueName('Test (1)',[{name:'Test (1)'}]),'Test (1) (1)');
const longName='x'.repeat(100),numbered=longName.slice(0,96)+' (1)';
assert.equal(p.uniqueName(longName,[{name:longName}]),numbered);
assert.equal(p.uniqueName(longName,[{name:longName},{name:numbered}]),longName.slice(0,96)+' (2)');
assert.throws(()=>p.parse(link.replace('security=reality','security=reality&allowInsecure=1')));
assert.throws(()=>p.parse(link.replace('example.com:443','example.com:99999')));
assert.throws(()=>p.parse(link.replace('type=tcp','type=kcp')));
assert.throws(()=>p.parse(link.replace(uuid,'$(touch /tmp/bad)')));
assert.throws(()=>p.parse('incy://crypt1/foobar'));
assert.equal(p.parse('trojan://password@example.com:443?sni=example.org#Test').protocol,'trojan');
assert.equal(p.parse('ss://'+Buffer.from('aes-128-gcm:password').toString('base64')+'@example.com:443#SS').secret,'password');
assert.ok(n.install().includes('--mark 511 -j RETURN'));assert.ok(n.install().includes('-d 192.168.0.0/16 -j RETURN'));
assert.ok(!n.cleanup().includes('iptables -t nat -F;'));assert.ok(n.start('/tmp/sever','/tmp/core','tcp').includes('now-lease'));
assert.equal(n.quote("a'$(echo x)"),"'a'\\''$(echo x)'");
console.log('Profile parsing, Reality config, loop prevention, rollback scope and shell quoting: passed');
